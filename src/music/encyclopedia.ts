import type { ReviewQuestion } from '../state/theoryReview'
import type { TheoryStageId } from './theoryCatalog'

export type EncyclopediaType =
  | 'composer'
  | 'appreciation'
  | 'chinese-music'
  | 'western-history'
  | 'instrument'
  | 'genre-form'

export interface EncyclopediaQuiz {
  question: string
  options: string[]
  answer: number
  explanation: string
}

export interface EncyclopediaEntry {
  id: string
  type: EncyclopediaType
  title: string
  subtitle: string
  stage: TheoryStageId
  category: string
  summary: string
  /** 多段正文：背景、特点、代表作、听赏指引（扩写阶段注入） */
  detail?: string
  keyFacts: string[]
  prompt: string
  relatedTheoryIds: string[]
  quiz: EncyclopediaQuiz[]
}

export interface EncyclopediaFilter {
  type?: EncyclopediaType
  category?: string
  stage?: TheoryStageId
  search?: string
}

export const ENCYCLOPEDIA_CATEGORIES: { type: EncyclopediaType; label: string }[] = [
  { type: 'composer', label: '音乐家' },
  { type: 'appreciation', label: '作品与欣赏' },
  { type: 'chinese-music', label: '中国传统音乐' },
  { type: 'western-history', label: '西方音乐史' },
  { type: 'instrument', label: '乐器' },
  { type: 'genre-form', label: '体裁与曲式' },
]

function entry(
  id: string,
  type: EncyclopediaType,
  title: string,
  subtitle: string,
  stage: TheoryStageId,
  summary: string,
  keyFacts: string[],
  prompt: string,
  relatedTheoryIds: string[],
  ...rest: [...string[], EncyclopediaQuiz[]]
): EncyclopediaEntry {
  const category = ENCYCLOPEDIA_CATEGORIES.find((item) => item.type === type)?.label ?? type
  const quiz = rest[rest.length - 1] as EncyclopediaQuiz[]
  const detail = rest.slice(0, rest.length - 1).join('\n\n')
  return {
    id,
    type,
    title,
    subtitle,
    stage,
    category,
    summary,
    detail,
    keyFacts,
    prompt,
    relatedTheoryIds,
    quiz,
  }
}

